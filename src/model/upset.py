"""波乱確率＝万車券率（三連単の払戻が10,000円以上になる確率）。

**旧表示の何が問題だったか**: ダッシュボードは `1 - 本命の1着確率` を「波乱」と出していた。
これは「本命が1着を外す確率」であって高配当になる確率ではない。本命が飛んでも
2番人気→3番人気で決まれば配当は安い。実測との乖離は大きく、男子25,335Rで
**平均予測 57.97% に対し実測の万車券率は 28.91%**（約2倍の過大表示）だった。

**採用した推定量**: 控除率25%なので 配当 ≈ TAKEOUT / p。10,000円（100円あたり100倍）に
なるのは p <= 0.75/100 = 0.0075 の目。モデルの三連単分布のうち、その帯に載っている
確率を合計する。オッズが要らないので発売前でも出せる。

検証（`scripts/validate_upset_prob.py`, walk-forward 5fold, 事前登録した基準）:
  男子   平均予測 31.43% / 実測 28.91% / ECE 0.0278 / Brier 0.1974（定数予測に5/5勝ち）
         十分位の実測 14→19→21→23→26→30→30→36→41→48% と単調増加
  主基準(ECE<=0.03 かつ 過半foldで定数予測にBrier勝ち)・副基準(単調) とも充足 → 採用

**モデル分布×実オッズ**（市場が100倍以上に値付けした目の確率を合計）も試したが、
平均50.30%と大きく過大で不採用。モデルは市場よりも裾に確率を置きすぎている＝
市場の方が裾の値付けは正確、という含意がある。
"""
from __future__ import annotations

MAN_YEN = 10000            # 万車券のしきい（100円あたりの払戻）
TAKEOUT = 0.75             # 控除率25%。配当 ≈ TAKEOUT / p
# この確率以下の目が万車券圏。0.0075
P_MAN = TAKEOUT / (MAN_YEN / 100)


def man_prob(probs: dict[tuple, float] | None) -> float | None:
    """三連単の全通り確率 → 万車券になる確率。probs が無ければ None。

    probs は {(1着,2着,3着): p}。合計1になっている前提（all_trifecta_probs の出力）。
    """
    if not probs:
        return None
    return round(sum(p for p in probs.values() if p <= P_MAN), 4)
